I18N& I18N::instance() {
    static I18N inst;
    return inst;
}

I18N::I18N() {
    buildEn();
    buildRu();
    buildUk();
}

void I18N::setLanguage(const QString& lang) {
    if (m_dict.contains(lang)) m_lang = lang;
}

QString I18N::tr(const QString& key) const {
    auto it = m_dict.find(m_lang);
    if (it != m_dict.end()) {
        auto& map = *it;
        auto k = map.find(key);
        if (k != map.end()) return *k;
    }
    auto it2 = m_dict.find("en");
    if (it2 != m_dict.end()) {
        auto& map = *it2;
        auto k = map.find(key);
        if (k != map.end()) return *k;
    }
    return key;
}

